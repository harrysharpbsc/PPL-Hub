"""Generate the app's topic diagrams from the figure modules in this folder.

    python3 tools/diagrams/gen.py            # writes src/labs84gen.js and previews in tools/diagrams/out/

Each module defines TOPIC (a NOTES topic name) and FIGS: (slug, title, svg body, caption, section, w, h).
In the app every figure goes through dzF() (chart paper + figure card) inside <g class="pdg">, and sec()
puts it in the note section whose title starts with `section` (checked by tests/t_secdg.py).
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import pplsvg  # noqa: E402
import circuits  # noqa: E402
import overhead_join  # noqa: E402
import rules_of_the_air  # noqa: E402

MODULES = [circuits, overhead_join, rules_of_the_air]
ROOT = HERE.parents[1]


def js_file():
    out = ["/* GENERATED by tools/diagrams/gen.py from the modules in tools/diagrams/. Do not edit by hand:",
           "   change the module and run `python3 tools/diagrams/gen.py`. Style: .claude/skills/ppl-hub-diagrams. */",
           "(function(){",
           "function sec(topic,head,figs){DSEC[topic]=(DSEC[topic]||[]).concat(figs.map(function(f){return[head,f]}))}"]
    for m in MODULES:
        for slug, title, body, cap, section, w, h in m.FIGS:
            out.append(f"/* {slug} */")
            out.append(f"sec({json.dumps(m.TOPIC)},{json.dumps(section)},[dzF({json.dumps(title)},"
                       f"{json.dumps('<g class=\"pdg\">' + body + '</g>')},{json.dumps(cap)},{w},{h})]);")
    out.append("})();")
    return "\n".join(out) + "\n"


def previews():
    outdir = HERE / "out"
    outdir.mkdir(exist_ok=True)
    for old in list(outdir.glob("*.html")) + list(outdir.glob("*.svg")):
        old.unlink()
    for m in MODULES:
        figs = [(slug, t, f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" role="img" aria-label="{t}">'
                 + pplsvg.paper(w, h) + body + "</svg>", cap, sec, w, h) for slug, t, body, cap, sec, w, h in m.FIGS]
        pplsvg.page(outdir / f"{m.__name__}.html", figs, m.TOPIC, m.TOPIC, "Preview of the generated figures.", m.TOPIC)


if __name__ == "__main__":
    (ROOT / "src" / "labs84gen.js").write_text(js_file())
    previews()
    n = sum(len(m.FIGS) for m in MODULES)
    print(f"wrote src/labs84gen.js ({n} figures) and previews in tools/diagrams/out/")
